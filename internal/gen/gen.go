// Package gen writes the TypeScript the video renders from.
//
// The alternative designs both lose. A static JSON import needs a literal
// specifier per locale, so adding a language would mean editing TypeScript, and
// a missing manifest becomes a build error that stops Studio opening at all.
// Remotion's calculateMetadata resolves asynchronously on every Studio boot and
// every still, once per composition, to re-read a file that changes when
// someone runs text-to-speech — and a throw there removes the composition from
// the list entirely, which reads as "the video is gone".
//
// Generating a committed module keeps durations constant at registration and
// keeps ordinary hot-reload. Its one weakness is going stale, and that is
// closed by regenerating in memory and comparing bytes.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/cuongtranba/narrated-video/internal/config"
	"github.com/cuongtranba/narrated-video/internal/project"
)

const header = "// GENERATED by `nv sync` — do not edit.\n"

// File is generated content addressed by its path relative to the project root.
type File struct {
	Path string
	Data []byte
}

// All renders every generated file. It is pure: the same project state always
// produces the same bytes, which is what lets `nv validate` prove the committed
// files match the config and the measurements they claim to come from.
func All(p *project.Project) ([]File, error) {
	content, err := contentTS(p)
	if err != nil {
		return nil, err
	}
	files := []File{
		{Path: p.GeneratedPath("timeline.ts"), Data: timelineTS(p)},
		{Path: p.GeneratedPath("registry.ts"), Data: registryTS(p)},
		{Path: p.GeneratedPath("theme.ts"), Data: themeTS(p)},
		{Path: p.GeneratedPath("content.ts"), Data: content},
	}
	if len(p.Config.Diagrams) > 0 {
		files = append(files, File{Path: p.GeneratedPath("diagrams.ts"), Data: diagramsTS(p)})
	}
	return files, nil
}

func timelineTS(p *project.Project) []byte {
	cfg := p.Config
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(`
export type Source = "measured" | "estimated" | "literal"

export interface SceneTiming {
  readonly id: string
  readonly leadFrames: number
  readonly narrationFrames: number
  readonly tailFrames: number
  readonly durationInFrames: number
  readonly source: Source
  readonly hasAudio: boolean
}

export interface LocaleTimeline {
  readonly locale: string
  readonly fps: number
  readonly transitionFrames: number
  readonly scenes: readonly SceneTiming[]
  readonly totalFrames: number
  readonly complete: boolean
}

`)
	fmt.Fprintf(&b, "export const FPS = %d\n", cfg.Video.FPS)
	fmt.Fprintf(&b, "export const WIDTH = %d\n", cfg.Video.Width)
	fmt.Fprintf(&b, "export const HEIGHT = %d\n", cfg.Video.Height)
	fmt.Fprintf(&b, "export const DEFAULT_LOCALE = %s\n", quote(cfg.Locales.Default))

	codes := cfg.LocaleCodes()
	b.WriteString("export const LOCALES = [")
	for i, code := range codes {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(quote(code))
	}
	b.WriteString("] as const\n")
	b.WriteString("export type Locale = (typeof LOCALES)[number]\n\n")

	b.WriteString("export const COMPOSITION_ID: Readonly<Record<Locale, string>> = {\n")
	for _, code := range codes {
		fmt.Fprintf(&b, "  %s: %s,\n", tsKey(code), quote(cfg.CompositionID(code)))
	}
	b.WriteString("}\n\n")

	b.WriteString("export const TIMELINE: Readonly<Record<Locale, LocaleTimeline>> = {\n")
	for _, code := range codes {
		t := p.Timelines[code]
		fmt.Fprintf(&b, "  %s: {\n", tsKey(code))
		fmt.Fprintf(&b, "    locale: %s,\n", quote(t.Locale))
		fmt.Fprintf(&b, "    fps: %d,\n", t.FPS)
		fmt.Fprintf(&b, "    transitionFrames: %d,\n", t.TransitionFrames)
		b.WriteString("    scenes: [\n")
		for _, s := range t.Scenes {
			fmt.Fprintf(&b,
				"      { id: %s, leadFrames: %d, narrationFrames: %d, tailFrames: %d, durationInFrames: %d, source: %s, hasAudio: %t },\n",
				quote(s.ID), s.LeadFrames, s.NarrationFrames, s.TailFrames, s.DurationInFrames, quote(string(s.Source)), s.HasAudio)
		}
		b.WriteString("    ],\n")
		fmt.Fprintf(&b, "    totalFrames: %d,\n", t.TotalFrames)
		fmt.Fprintf(&b, "    complete: %t,\n", t.Complete)
		b.WriteString("  },\n")
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

// Components are bound at module scope here rather than resolved during render:
// a component identity created while rendering is a new type every frame, and
// React remounts the scene under it.
func registryTS(p *project.Project) []byte {
	ids := p.Config.SceneIDs()

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\nimport type { SceneComponent } from \"../scenes/types\"\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "import { Scene as %s } from \"../scenes/%s\"\n", id, id)
	}

	b.WriteString("\nexport const SCENE_ORDER = [")
	for i, id := range ids {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(quote(id))
	}
	b.WriteString("] as const\n")
	b.WriteString("export type SceneId = (typeof SCENE_ORDER)[number]\n\n")

	b.WriteString("export const SCENE_COMPONENTS: Readonly<Record<SceneId, SceneComponent>> = {\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "  %s,\n", id)
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

func themeTS(p *project.Project) []byte {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\nexport const THEME = {\n")
	for _, name := range project.SortedKeys(p.Config.Theme) {
		fmt.Fprintf(&b, "  %s: %s,\n", tsKey(name), quote(p.Config.Theme[name]))
	}
	b.WriteString("} as const\n")
	return []byte(b.String())
}

// contentTS derives the Copy type from the DEFAULT locale's structure, so
// adding a field on screen is a YAML edit and TypeScript learns its shape for
// free. A translation that drops or renames a key then fails to compile rather
// than rendering an empty box.
func contentTS(p *project.Project) ([]byte, error) {
	cfg := p.Config
	defaultCopy := p.Content[cfg.Locales.Default].Copy

	copyType, err := tsType(defaultCopy, 0)
	if err != nil {
		return nil, fmt.Errorf("deriving Copy from the %s content: %w", cfg.Locales.Default, err)
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\nimport type { Locale } from \"./timeline\"\nimport type { SceneId } from \"./registry\"\n\n")
	fmt.Fprintf(&b, "export interface Copy %s\n\n", copyType)

	b.WriteString("export const NARRATION: Readonly<Record<Locale, Readonly<Partial<Record<SceneId, string>>>>> = {\n")
	for _, code := range cfg.LocaleCodes() {
		narration := p.Content[code].Narration
		fmt.Fprintf(&b, "  %s: {\n", tsKey(code))
		for _, scene := range project.SortedKeys(narration) {
			fmt.Fprintf(&b, "    %s: %s,\n", tsKey(scene), quote(narration[scene]))
		}
		b.WriteString("  },\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("export const COPY: Readonly<Record<Locale, Copy>> = {\n")
	for _, code := range cfg.LocaleCodes() {
		literal, err := tsValue(p.Content[code].Copy, 2)
		if err != nil {
			return nil, fmt.Errorf("rendering the %s copy: %w", code, err)
		}
		fmt.Fprintf(&b, "  %s: %s,\n", tsKey(code), literal)
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}

func diagramsTS(p *project.Project) []byte {
	cfg := p.Config
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(`
import type { Locale } from "./timeline"

export interface DiagramNode {
  readonly id: string
  readonly x: number
  readonly y: number
  readonly width: number
  readonly height: number
  readonly label: string
}

export interface DiagramEdge {
  readonly id: string
  readonly source: string
  readonly target: string
}

export interface DiagramData {
  readonly nodes: readonly DiagramNode[]
  readonly edges: readonly DiagramEdge[]
}

export const DIAGRAMS: Readonly<Record<Locale, Readonly<Record<string, DiagramData>>>> = {
`)
	for _, code := range cfg.LocaleCodes() {
		fmt.Fprintf(&b, "  %s: {\n", tsKey(code))
		copyMap := p.Content[code].Copy
		diagramLabels, _ := copyMap["diagrams"].(map[string]any)
		for _, name := range project.SortedKeys(cfg.Diagrams) {
			d := cfg.Diagrams[name]
			fmt.Fprintf(&b, "    %s: {\n", tsKey(name))
			b.WriteString("      nodes: [\n")
			nodes := make([]config.DiagramNode, len(d.Nodes))
			copy(nodes, d.Nodes)
			sort.Slice(nodes, func(i, j int) bool { return nodes[i].ID < nodes[j].ID })
			for _, node := range nodes {
				label := diagramLabel(diagramLabels, name, node.ID)
				fmt.Fprintf(&b,
					"        { id: %s, x: %s, y: %s, width: %s, height: %s, label: %s },\n",
					quote(node.ID),
					formatNumber(node.At[0]),
					formatNumber(node.At[1]),
					formatNumber(node.Size[0]),
					formatNumber(node.Size[1]),
					quote(label),
				)
			}
			b.WriteString("      ],\n")
			b.WriteString("      edges: [\n")
			for _, edge := range d.Edges {
				fmt.Fprintf(&b,
					"        { id: %s, source: %s, target: %s },\n",
					quote(edge.From+"-"+edge.To),
					quote(edge.From),
					quote(edge.To),
				)
			}
			b.WriteString("      ],\n")
			b.WriteString("    },\n")
		}
		b.WriteString("  },\n")
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

func diagramLabel(diagramLabels map[string]any, diagramName, nodeID string) string {
	if diagramLabels == nil {
		return ""
	}
	labels, _ := diagramLabels[diagramName].(map[string]any)
	if labels == nil {
		return ""
	}
	label, _ := labels[nodeID].(string)
	return label
}

func formatNumber(f float64) string {
	if f == float64(int64(f)) {
		return fmt.Sprintf("%d", int64(f))
	}
	return fmt.Sprintf("%g", f)
}

// tsType walks a value and describes its shape. Keys are sorted so the output
// is byte-stable; authoring order is not preserved anywhere in generated code.
func tsType(v any, depth int) (string, error) {
	pad := strings.Repeat("  ", depth+1)
	closePad := strings.Repeat("  ", depth)

	switch typed := v.(type) {
	case string:
		return "string", nil
	case bool:
		return "boolean", nil
	case int, int64, float64:
		return "number", nil

	case []any:
		if len(typed) == 0 {
			// Nothing to learn the element type from. `unknown` keeps the
			// build honest instead of guessing `string[]` and being wrong.
			return "readonly unknown[]", nil
		}
		seen := map[string]bool{}
		var members []string
		for _, item := range typed {
			t, err := tsType(item, depth)
			if err != nil {
				return "", err
			}
			if !seen[t] {
				seen[t] = true
				members = append(members, t)
			}
		}
		sort.Strings(members)
		if len(members) == 1 {
			return "readonly " + members[0] + "[]", nil
		}
		return "readonly (" + strings.Join(members, " | ") + ")[]", nil

	case map[string]any:
		var b strings.Builder
		b.WriteString("{\n")
		for _, key := range project.SortedKeys(typed) {
			field, err := tsType(typed[key], depth+1)
			if err != nil {
				return "", fmt.Errorf("%s: %w", key, err)
			}
			fmt.Fprintf(&b, "%sreadonly %s: %s\n", pad, tsKey(key), field)
		}
		fmt.Fprintf(&b, "%s}", closePad)
		return b.String(), nil

	case nil:
		return "", fmt.Errorf("null has no type to derive — give the field a value or remove it")
	}
	return "", fmt.Errorf("unsupported value %T", v)
}

func tsValue(v any, depth int) (string, error) {
	pad := strings.Repeat("  ", depth+1)
	closePad := strings.Repeat("  ", depth)

	switch typed := v.(type) {
	case map[string]any:
		var b strings.Builder
		b.WriteString("{\n")
		for _, key := range project.SortedKeys(typed) {
			field, err := tsValue(typed[key], depth+1)
			if err != nil {
				return "", fmt.Errorf("%s: %w", key, err)
			}
			fmt.Fprintf(&b, "%s%s: %s,\n", pad, tsKey(key), field)
		}
		fmt.Fprintf(&b, "%s}", closePad)
		return b.String(), nil

	case []any:
		var parts []string
		for _, item := range typed {
			rendered, err := tsValue(item, depth+1)
			if err != nil {
				return "", err
			}
			parts = append(parts, rendered)
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	}

	// Scalars are valid TypeScript as JSON, escaping included.
	encoded, err := json.Marshal(v)
	if err != nil {
		return "", err
	}
	return string(encoded), nil
}

func quote(s string) string {
	encoded, err := json.Marshal(s)
	if err != nil {
		return `""`
	}
	return string(encoded)
}

// tsKey quotes anything that is not a plain identifier. Scene ids and locale
// codes are constrained by the schema, but copy keys are the author's to choose.
func tsKey(name string) string {
	if isIdentifier(name) {
		return name
	}
	return quote(name)
}

func isIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		isLetter := r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
		if isLetter {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}

// Diff reports which generated files on disk differ from a fresh derivation.
// Byte equality is the whole point: a scene that drifted by fourteen frames
// looks fine in every frame of the render, and only the comparison catches it.
func Diff(p *project.Project, read func(string) ([]byte, error)) ([]string, error) {
	files, err := All(p)
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, f := range files {
		onDisk, err := read(f.Path)
		if err != nil || !bytes.Equal(onDisk, f.Data) {
			stale = append(stale, f.Path)
		}
	}
	return stale, nil
}
